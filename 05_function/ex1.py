# - 엄마한테 받은 돈 : 5000원 => 키워드 가변인자 (딕셔너리)

def pocket_money(a,*args,**kwargs):
    print(a+sum(args)+sum(kwargs.values()))
    pass

pocket_money(500,100,200,mom=5000,dad=10000,)
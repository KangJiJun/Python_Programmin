def add(a,b):
    """returns a + b"""
    return a+b #__add__()

print(add(3,4))
print(add("hello","python"))
print(add([1,2],[3,4]))
print(add((1,2),(3,4)))
print(add.__doc__)


# ===========================================================
# 2. 튜플을 리턴하는 함수
# ===========================================================

def ass(a,b):
    return a+b,a-b
print(ass(1,3))
print(*ass(1,3))


# ===========================================================
# 3. 디폴트 매개변수 (Default Parameter)
# ===========================================================
# 매개변수에 기본값을 지정하면, 호출 시 해당 인자를 생략할 수 있다.
# 디폴트 매개변수는 항상 일반 매개변수 뒤에 위치해야 한다.

def add(a,b=0):
    return a+b

print(add(5,10))
print(add(5))


# ===========================================================
# 4. 키워드 인자 (Keyword Argument)
# ===========================================================
# 인자를 순서가 아니라 "매개변수명=값" 형태로 전달할 수 있다.
# 순서를 바꿔서 호출해도 이름만 맞으면 정확히 전달된다.

print(add(5,10))
print(add(b=10,a=5))

def itrdc(nm,ag,ct="Paris"):
    return f"I'm {nm}, {ag} years old, live in {ct}"
print(itrdc(nm="Marinette",ag=14,ct="Paris"))
print(itrdc(nm="Adrien",ag=14))


# ===========================================================
# 5. 가변 인자 (Variable-length Argument, *args)
# ===========================================================
# 몇 개의 인자가 들어올지 모를 때 *args를 사용한다. (관례적으로 사용)
# args라는 이름으로 입력값들을 모아 튜플로 만든다.

def aal(*args):
    print(args)
    return sum(args)
print(aal(1,2,3))
print(aal(1,2,3,4,5))
print(aal(*[1,2,3]))

# ================================================================
# 6. 키워드 가변 인자 (Keyword Variable-length Argument, **kwargs)
# ================================================================
# 이름=값 형태로 몇 개가 들어올지 모를 때 **kwargs를 사용한다.
# kwargs라는 이름으로 입력값들을 모아 딕셔너리로 만든다.

def itrdc2(**kwargs):
    print(kwargs)

d = {"name": "크롱", "age": 4, "kind": "공룡"}

itrdc2(nm="marinette",ag=14,kind="미소녀",home="빵집")
itrdc2(**d)


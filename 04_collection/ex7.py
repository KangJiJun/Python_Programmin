# 집합 기초

# ===========================================================
#  집합 (set): 여러 객체를 순서 없이 중복을 허용하지 않고 저장하는 변경 가능한 자료형
#  집합의 특징
#  1. ( mutable )
#  2. ( iterable )
#  3. ( unsequencable )
#  4. ( duplication not allowed )
# ===========================================================

# 집합 생성
# a = {}
a = set()
print(type(a))

a={3,3,3,2,2,1}
print(a)
b={100,8,30}
print(b)

# ===========================================================
# 1. 집합은 mutable하다. (변경 가능)
# ===========================================================
a.update({3,4})
print(a)

a.remove(3)
# a.pop()
print(a)



# ===========================================================
# 2. 집합은 iterable하다. (반복 가능)
# ===========================================================

# 집합 순회



# ===========================================================
# 3. 집합은 sequence 객체가 아니다. (인덱싱, 슬라이싱 불가)
# ===========================================================



# ===========================================================
# 4. 집합은 중복을 허용하지 않는다.
# ===========================================================

s={10,10,20,30,40}

# ===========================================================
#  파이썬 내장 함수
# ===========================================================

print(len(s))
print(sum(s))
print(min(s),max(s))
print(sorted(s))


# 집합 합치기
s2={40,50}
print(s.union(s2))

# 집합 반복하기


# 멤버십 연산자
print(10 in s)
print(1 in s)